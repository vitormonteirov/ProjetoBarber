CREATE TABLE bloqueio_agenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id BIGINT NOT NULL,
    data_hora_inicio TIMESTAMP NOT NULL,
    data_hora_fim TIMESTAMP NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    criado_por VARCHAR(150),
    CONSTRAINT fk_bloqueio_barbeiro FOREIGN KEY (barbeiro_id) REFERENCES barbeiro(id)
);

CREATE INDEX idx_bloqueio_barbeiro_periodo ON bloqueio_agenda(barbeiro_id, data_hora_inicio, data_hora_fim);

